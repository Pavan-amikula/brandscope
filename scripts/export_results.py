"""Create recruiter-readable outputs from the committed aggregate snapshot."""
import csv
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
d=json.loads((ROOT/'web/data.json').read_text(encoding='utf-8'))
dest=ROOT/'docs/outputs';dest.mkdir(exist_ok=True)
all_data=d['markets']['All markets']['full']
for name,rows in [('segments',all_data['segments']),('products',all_data['products']),
                  ('monthly_sales',all_data['monthly']),('ranking_evaluation',d['evaluation'])]:
    with (dest/f'{name}.csv').open('w',encoding='utf-8',newline='') as f:
        writer=csv.DictWriter(f,fieldnames=list(rows[0]));writer.writeheader();writer.writerows(rows)
k=all_data['kpis'];risk=next(s for s in all_data['segments'] if s['segment']=='At risk · high value')
report=f'''# BrandScope — measured results

Source: Chen (2015), UCI Online Retail, CC BY 4.0. Rebuilt from the entire workbook.

| Historical metric | Result |
| --- | ---: |
| Raw source rows | {d['quality']['raw_rows']:,} |
| Retained merchandise rows | {d['quality']['retained_rows']:,} |
| Gross merchandise sales | £{k['gross_sales']:,.2f} |
| Recorded returns | £{k['returns']:,.2f} |
| Net merchandise sales | £{k['net_sales']:,.2f} |
| Purchase orders | {k['orders']:,} |
| Identified shoppers | {k['customers']:,} |
| Repeat shopper rate | {100*k['repeat_rate']:.2f}% |
| High-value inactive shoppers | {risk['customers']:,} |
| Their historical gross sales | £{risk['revenue']:,.2f} |

These are historical descriptive metrics, not revenue generated by this project. The inactive shoppers' spend is not guaranteed recoverable value.

## Temporal repurchase ranking

| Cutoff | Eligible shoppers | Targeted shoppers | Overall repurchase | RFM precision | Spend-only precision | RFM / overall |
| --- | ---: | ---: | ---: | ---: | ---: | ---: |
'''
for r in d['evaluation']:
    report+=f"| {r['cutoff']} | {r['eligible']:,} | {r['targeted']:,} | {100*r['overall_repurchase_rate']:.2f}% | {100*r['rfm_precision']:.2f}% | {100*r['monetary_precision']:.2f}% | {r['ranking_lift']:.2f}× |\n"
report+='''
Past-only RFM features rank customers for a subsequent 30-day purchase window. RFM precision exceeds the spend-only baseline on each of these three checks, with a modest advantage on the final cutoff. No model tuning, significance test, probability calibration or causal campaign outcome is claimed. The populations overlap across windows.

## Commercial scenario, not measured business impact

The default scenario produces £255 modelled incremental contribution; increasing the discount from 5% to 20% changes the result to −£825. Both assume 2,000 shoppers, 5% baseline conversion, a 3 percentage-point gain, £45 order value, 45% margin and £600 campaign cost. The approximate conversion sample requirement is 1,059 per arm, exceeding that 2,000-person total audience. This is a useful **do not scale yet** decision, not a manufactured success claim.

## Swedish scope

The Swedish subset has eight identified shoppers and 34 purchase orders, with £35,166.41 net merchandise sales. It is a UK retailer's export sample, not a representative Swedish consumer-goods market sample.

## Reproduce

Run `python scripts/build_data.py`, then `python scripts/export_results.py`. Raw source and local SQLite files are ignored by Git. Formula, cohort, segment and evaluation definitions are in `docs/METHODS.md`.
'''
(dest/'RESULTS.md').write_text(report,encoding='utf-8')
print('Exported CSVs and measured results to docs/outputs/')
